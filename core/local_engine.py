def _level(samples) -> float:
    try:
        x = np.asarray(samples, dtype=np.float32)
        if x.size == 0:
            return 0.0
        rms = float(np.sqrt(np.mean(x * x)))
    except Exception:
        return 0.0
    if rms <= 60.0:
        return 0.0
    return min(1.0, (rms - 60.0) / 2540.0)


@dataclass
class Request:
    text: str
    source: str = "voice"            # voice | typed | system | remote
    images: list = field(default_factory=list)
    lang: str = ""


class LocalSession:
    """Accepts the calls main.py makes on a Gemini Live session."""

    def __init__(self, eng: "LocalEngineMixin"):
        self._eng = eng

    async def send_client_content(self, turns=None, turn_complete=True, **_kw):
        texts, images = [], []
        items = turns if isinstance(turns, (list, tuple)) else [turns]
        for t in items:
            if not isinstance(t, dict):
                continue
            for p in t.get("parts") or []:
                if not isinstance(p, dict):
                    continue
                if p.get("text"):
                    texts.append(str(p["text"]))
                elif isinstance(p.get("inline_data"), dict):
                    d = p["inline_data"]
                    images.append({"mime": d.get("mime_type", "image/jpeg"), "data": d.get("data", "")})
        if texts or images:
            self._eng._submit("\n".join(texts), images=images, source="system")

    async def send_realtime_input(self, audio=None, **_kw):
        data = getattr(audio, "data", None)
        if data is None and isinstance(audio, dict):
            data = audio.get("data")
        if data:
            self._eng._feed_remote_audio(data)

    async def send_tool_response(self, **_kw):
        return None

    async def receive(self):          # never used by the local engine
        if False:
            yield None


class LocalEngineMixin:
    """Mixed in before JarvisLive: `class LocalJarvis(LocalEngineMixin, JarvisLive)`."""

    INLINE_TOOLS: list = []

    # ── construction ─────────────────────────────────────────────────────────
    def __init__(self, ui):
        super().__init__(ui)
        self.engine_kind = "local"
        self._history: list[dict] = []
        self._earlier = ""                 # digest of history that no longer fits
        self._hist_lock = threading.RLock()
        self._req_q: asyncio.Queue | None = None
        self._mic_q: queue.Queue = queue.Queue(maxsize=600)
        self._utt_q: queue.Queue = queue.Queue(maxsize=12)
        self._tts_q: queue.Queue = queue.Queue()
        self._tts_pending = 0
        self._tts_cond = threading.Condition()
        self._cancel = threading.Event()
        self._turn_id = 0
        self._busy = False
        self._stt = None
        self._stt_cfg = None
        self._stt_ready = threading.Event()
        self._tts = None
        self._segmenter = None
        self._seg_during = False
        self._spoken: collections.deque = collections.deque(maxlen=40)
        self._last_reply_end = 0.0
        self._last_lang = ""
        self._workers = False
        self._brain_ok = False
        self._pull_started: set[str] = set()
        self._stt_wait_note = 0.0
        self._asst_name = brain_config.assistant_name()
        runtime.set_engine(self)

    # ── what the rest of the app calls ───────────────────────────────────────
    def _all_tool_decls(self) -> list:
        decls = list(self.INLINE_TOOLS) + self._action_registry.get_tool_declarations() \
            + self._plugin_registry.get_tool_declarations()
        try:
            from core import mcp_client
            decls += mcp_client.manager().gemini_declarations()
        except Exception:
            pass
        b = brain_config.get_brain()
        disabled = set(b.get("disabled_tools") or [])
        profile = str(b.get("tool_profile") or "auto").lower()
        if profile == "auto" and b.get("provider") in ("ollama", "lmstudio"):
            size = llm.model_size_b(llm.settings_for("chat"))
            profile = "lean" if (size is not None and size < 6.5) else "full"
        if profile == "lean":
            disabled |= set(brain_config.LEAN_HIDDEN)
        return [d for d in decls if d.get("name") not in disabled]

    def _submit(self, text: str, images=None, source: str = "system", lang: str = "") -> None:
        req = Request(text=text or "", source=source, images=list(images or []), lang=lang)
        loop = self._loop
        if loop is None or self._req_q is None:
            return
        try:
            loop.call_soon_threadsafe(self._req_q.put_nowait, req)
        except RuntimeError:
            pass

    def _on_text_command(self, text: str):
        if not self._loop or not self.session:
            return
        if self._wake_enabled and not self._awake:
            self.ui.write_log("SYS: I'm asleep — say 'Hey Jarvis' or tap WAKE NOW first.")
            return
        if self._is_speaking or self._busy:
            self.interrupt()
        self._last_user_speech = time.monotonic()
        self._session_log.append(f"User: {text}")
        journal.append("user", text, True, via="typed")
        self._submit(text, source="typed")

    def speak_error(self, tool_name: str, error: str):
        # The error already goes back to the model as the tool result, inside
        # the same turn; a second, separate "tell the user" turn is noise here.
        self.ui.write_log(f"ERR: {tool_name} — {str(error)[:120]}")

    def plugin_say(self, instruction: str) -> None:
        """A plugin wants something said while its tool is still running."""
        if not self._busy:
            self._submit(instruction, source="system")
            return

        def work():
            try:
                line = llm.complete(
                    f"Turn this instruction into ONE short sentence to say to the user, "
                    f"in {self._lang_name()}. Output only the sentence.\n\n{instruction}",
                    role="fast", max_tokens=80, timeout=20)
            except Exception:
                line = ""
            if line:
                self._speak(line.strip().strip('"'), self._turn_id)
        threading.Thread(target=work, daemon=True).start()

    def interrupt(self) -> None:
        self._cancel.set()
        self._turn_id += 1
        try:
            while True:
                self._tts_q.get_nowait()
                with self._tts_cond:
                    self._tts_pending = max(0, self._tts_pending - 1)
                    self._tts_cond.notify_all()
        except queue.Empty:
            pass
        super().interrupt()

    def set_speaking(self, value: bool):
        was = self._is_speaking
        super().set_speaking(value)
        if was and not value:
            self._last_reply_end = time.monotonic()

    def reload_plugins(self) -> str:
        from core.plugin_loader import discover_plugins
        base = Path(__file__).resolve().parent.parent
        core_names = {t["name"] for t in self.INLINE_TOOLS} | self._action_registry.names()
        self._plugin_registry = discover_plugins(
            plugins_dir=base / "plugins", core_tool_names=core_names,
            logger=lambda m: print(f"[Plugins] {m}"),
            notify=lambda m: self.ui.write_log(f"SYS: {m}"))
        self.ui.get_plugins = self._plugin_registry.list_for_ui
        self.ui.get_plugin_settings = self._plugin_registry.settings_schemas
        n = len(self._plugin_registry.get_tool_declarations())
        return f"Reloaded plugins: {n} active."


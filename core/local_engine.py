    def _system_prompt(self) -> str:
        from main import _describe_limits, _render_prompt   # noqa: PLC0415
        from memory.memory_manager import format_memory_for_prompt, load_memory
        base = Path(__file__).resolve().parent
        try:
            tmpl = (base / "prompt_local.txt").read_text(encoding="utf-8")
        except Exception:
            tmpl = "You are {assistant_name}, a helpful voice assistant on {platform}. Today is {date}."
        cfg = {}
        try:
            cfg = json.loads(brain_config.CONFIG_FILE.read_text(encoding="utf-8"))
        except Exception:
            pass
        self._asst_name = (cfg.get("assistant_name") or "JARVIS").strip()
        user = (cfg.get("user_name") or "").strip()
        body = _render_prompt(tmpl, {
            "assistant_name": self._asst_name,
            "platform": f"{platform.system()} {platform.release()}",
            "date": datetime.now().strftime("%A, %d %B %Y"),
            "limits": _describe_limits(has_vision=True, has_mic=True),
        })
        addr = (f"Call the user '{user}'." if user else
                "Address the user respectfully (\"sir\" in English, the natural equivalent in other languages).")
        parts = [f"[IDENTITY]\nYour name is {self._asst_name}. {addr}"]
        try:
            mem = format_memory_for_prompt(load_memory())
            if mem:
                parts.append(mem)
        except Exception:
            pass
        parts.append(body)
        if self._earlier:
            parts.append("[EARLIER IN THIS CONVERSATION]\n" + self._earlier)
        return "\n\n".join(parts)

    def _trim_history(self, num_ctx: int) -> None:
        budget = int(num_ctx * 1.3)
        with self._hist_lock:
            h = self._history
            # Images are expensive: keep them only in the latest exchange.
            last_user = max((i for i, m in enumerate(h) if m.get("role") == "user"), default=-1)
            for i, m in enumerate(h):
                if i < last_user and m.get("images"):
                    m.pop("images", None)
                    m["content"] = str(m.get("content", "")) + " [image no longer attached]"

            def size() -> int:
                return sum(len(str(m.get("content") or "")) + 80 * len(m.get("tool_calls") or [])
                           for m in h)
            dropped = []
            while size() > budget:
                starts = [i for i, m in enumerate(h) if m.get("role") == "user"]
                if len(starts) < 2:
                    break
                cut = starts[1]
                dropped.extend(h[:cut])
                del h[:cut]
            if dropped:
                notes = []
                for m in dropped:
                    c = visible_text(str(m.get("content") or ""))
                    if m.get("role") == "user" and c:
                        notes.append("User: " + c[:160])
                    elif m.get("role") == "assistant" and c:
                        notes.append("You: " + c[:160])
                self._earlier = ("\n".join(([self._earlier] if self._earlier else []) + notes))[-1500:]

    def _speak(self, sentence: str, turn_id: int) -> None:
        sentence = (sentence or "").strip()
        if not sentence:
            return
        self._spoken.append((time.monotonic(), sentence))
        with self._tts_cond:
            self._tts_pending += 1
        self._tts_q.put((turn_id, sentence, self._last_lang))

    def _wait_tts(self, turn_id: int, timeout: float = 180.0) -> None:
        deadline = time.monotonic() + timeout
        with self._tts_cond:
            while self._tts_pending > 0 and time.monotonic() < deadline:
                if turn_id != self._turn_id:
                    return
                self._tts_cond.wait(timeout=0.25)

    def _tts_worker(self) -> None:
        while True:
            tid, text, lang = self._tts_q.get()
            try:
                if tid != self._turn_id or self._tts is None:
                    continue
                first = True
                for chunk in self._tts.synth(text, lang):
                    if tid != self._turn_id:
                        break
                    self._call_in_loop(self._enqueue_audio, tid, chunk, text if first else "")
                    first = False
            except Exception as e:
                print(f"[Local] TTS error: {e}")
                self._log_async(f"ERR: Voice output — {str(e)[:120]}")
            finally:
                with self._tts_cond:
                    self._tts_pending = max(0, self._tts_pending - 1)
                    self._tts_cond.notify_all()

    def _enqueue_audio(self, tid: int, pcm: np.ndarray, text: str) -> None:
        if tid != self._turn_id or self.audio_in_queue is None:
            return
        if self._turn_done_event is not None and self._turn_done_event.is_set():
            self._turn_done_event.clear()
        if text:
            self._visemes.feed_text(text)
        data = np.asarray(pcm, dtype=np.int16).tobytes()
        for i in range(0, len(data), _SLICE):
            self.audio_in_queue.put_nowait(data[i:i + _SLICE])

    def _finish_turn_audio(self) -> None:
        if self._turn_done_event is not None:
            self._turn_done_event.set()

    async def _brain_loop(self):
        while True:
            req = await self._req_q.get()
            # Several things said in a row while we were busy become one request.
            while not self._req_q.empty():
                nxt = self._req_q.get_nowait()
                if nxt.source in ("voice", "typed") and req.source in ("voice", "typed") and not nxt.images:
                    req.text = f"{req.text} {nxt.text}".strip()
                else:
                    await self._run_turn(req)
                    req = nxt
            await self._run_turn(req)

    async def _run_turn(self, req: Request) -> None:
        if not req.text and not req.images:
            return
        self._busy = True
        self._cancel.clear()
        self._turn_id += 1
        tid = self._turn_id
        self._visemes.reset()
        if self._turn_done_event is not None:
            self._turn_done_event.clear()
        self.ui.set_state("THINKING")
        try:
            final = await asyncio.to_thread(self._agent_turn, req, tid)
        except Exception as e:
            traceback.print_exc()
            final = ""
            self.ui.write_log(f"ERR: {str(e)[:200]}")
        finally:
            self._busy = False
        # Let the voice finish before the turn is marked done.
        await asyncio.to_thread(self._wait_tts, tid)
        if tid == self._turn_id:
            self._finish_turn_audio()
            if not self._is_speaking and self.audio_in_queue is not None and self.audio_in_queue.empty():
                if not self.ui.muted:
                    self.ui.set_state("LISTENING")
                self._last_reply_end = time.monotonic()
        shown = "\n".join(getattr(self, "_turn_shown", []) or []).strip()
        if shown and "```" in shown:
            try:
                self.ui.show_content("REPLY", shown)
            except Exception:
                pass
        if final:
            self.ui.write_log(f"{self._asst_name}: {final}")
            self._session_log.append(f"{self._asst_name}: {final}")
            journal.append(self._asst_name, final, None)
            runtime.emit_assistant_text(final)
            if self._dashboard:
                asyncio.create_task(self._dashboard.broadcast({
                    "type": "log", "speaker": "jarvis", "text": final,
                    "ts": datetime.now().isoformat()}))
        if self._vision_close_pending:
            self._vision_close_pending = False

            async def _close():
                await asyncio.sleep(2.0)
                self.ui.stop_camera_stream()
            asyncio.create_task(_close())

    def _agent_turn(self, req: Request, tid: int) -> str:
        """One request, possibly many tool rounds. Runs in a worker thread."""
        b = brain_config.get_brain()
        s = llm.settings_for("chat")
        decls = self._all_tool_decls()
        params_by_name = {d.get("name"): d.get("parameters") for d in decls}
        now = datetime.now().strftime("%H:%M")
        user_msg: dict = {"role": "user", "content": f"{req.text}\n\n(time now {now})"
                          if req.source in ("voice", "typed") else req.text}
        if req.images:
            user_msg["images"] = req.images
        with self._hist_lock:
            self._history.append(user_msg)
        self._trim_history(s.num_ctx)
        spoken_all: list[str] = []
        self._turn_shown = []
        acked = False
        max_steps = int(b.get("max_steps", 10))
        tool_limit = max(1500, min(6000, int(s.num_ctx * 0.35)))

        for step in range(max_steps):
            if tid != self._turn_id or self._cancel.is_set():
                return " ".join(spoken_all)
            with self._hist_lock:
                msgs = [{"role": "system", "content": self._system_prompt()}] + list(self._history)
            stream = SpeechStream()
            final_ev = None
            try:
                for ev in llm.stream_chat(msgs, decls, s=s, cancel=self._cancel):
                    if ev.kind == "text":
                        for sentence in stream.feed(ev.text):
                            spoken_all.append(sentence)
                            self._speak(sentence, tid)
                    else:
                        final_ev = ev
            except llm.ProviderUnreachable as e:
                self._brain_ok = False
                msg = "I can't reach my brain right now."
                self.ui.write_log(f"ERR: {e}")
                self._speak(msg, tid)
                with self._hist_lock:
                    if self._history and self._history[-1] is user_msg:
                        self._history.pop()
                return msg
            except Exception as e:
                self.ui.write_log(f"ERR: Brain — {str(e)[:220]}")
                msg = "Something went wrong with the model: " + str(e)[:100]
                self._speak("Something went wrong with the model.", tid)
                with self._hist_lock:
                    if self._history and self._history[-1] is user_msg:
                        self._history.pop()
                return msg
            if final_ev is None or final_ev.cancelled:
                for sentence in stream.flush():
                    spoken_all.append(sentence)
                    self._speak(sentence, tid)
                return " ".join(spoken_all)
            for sentence in stream.flush():
                spoken_all.append(sentence)
                self._speak(sentence, tid)

            text = llm.strip_thinking(visible_text(final_ev.text))
            if text:
                self._turn_shown.append(text)
            calls = final_ev.tool_calls
            with self._hist_lock:
                self._history.append({"role": "assistant", "content": text,
                                      "tool_calls": [c.as_dict() for c in calls]} if calls
                                     else {"role": "assistant", "content": text})
            if not calls:
                return " ".join(spoken_all) or text

            if not spoken_all and not acked and any(c.name not in _INSTANT_TOOLS for c in calls):
                acked = True
                lang = self._last_lang if self._last_lang in _ACKS else "en"
                self._speak(random.choice(_ACKS[lang]), tid)

            self.ui.set_state("THINKING")
            for call in calls:
                if tid != self._turn_id or self._cancel.is_set():
                    break
                from core.tool_schema import coerce_arguments
                args = coerce_arguments(call.arguments, params_by_name.get(call.name))
                if call.name not in params_by_name:
                    result = (f"There is no tool named '{call.name}'. Use one of the listed tools.")
                else:
                    result = self._run_tool(call.name, args, call.id)
                extra_user = None
                if call.name == "screen_process" and self._pending_vision:
                    result, extra_user = self._resolve_vision(s)
                result = str(result)
                if len(result) > tool_limit:
                    result = result[:tool_limit] + f"\n…[truncated {len(result) - tool_limit} chars]"
                with self._hist_lock:
                    self._history.append({"role": "tool", "tool_call_id": call.id, "name": call.name,
                                          "content": result})
                    if extra_user:
                        self._history.append(extra_user)
        self._speak("I've stopped there — that took more steps than I allow myself. "
                    "Tell me if you want me to continue.", tid)
        return " ".join(spoken_all)

    def _run_tool(self, name: str, args: dict, call_id: str) -> str:
        if name == "shutdown_jarvis":
            return self._local_shutdown()
        loop = self._loop
        fc = SimpleNamespace(name=name, args=args, id=call_id or "")

        async def go():
            fr = await self._execute_tool(fc)
            resp = getattr(fr, "response", None) or {}
            return str(resp.get("result", "Done.")) if isinstance(resp, dict) else str(resp)
        try:
            return asyncio.run_coroutine_threadsafe(go(), loop).result()
        except Exception as e:
            return f"Tool '{name}' failed: {e}"

    def _local_shutdown(self) -> str:
        def bye():
            time.sleep(0.3)
            self._wait_tts(self._turn_id, timeout=8)
            time.sleep(1.0)
            try:
                fut = asyncio.run_coroutine_threadsafe(self._save_session_summary(), self._loop)
                fut.result(timeout=20)
            except Exception:
                pass
            import os
            os._exit(0)
        threading.Thread(target=bye, daemon=True).start()
        return "Shutting down now. Say a brief goodbye in one short sentence."

    def _resolve_vision(self, s: llm.Settings):
        """screen_process captured a frame: show it to a model that can see."""
        img_b, mime, question, angle = self._pending_vision
        self._pending_vision = None
        if self._vision_cam_active:
            self._vision_cam_active = False
            self._vision_close_pending = True
        self._vision_busy = False
        src = "WEBCAM" if angle == "camera" else "SCREEN CAPTURE"
        part = llm.image_part(img_b, mime)
        caps = llm.capabilities(s)
        vision_model = brain_config.get_brain().get("vision_model") or ""
        if caps.get("vision") and (not vision_model or vision_model == s.model):
            return ("The image is attached in the next message. Answer from what you see.",
                    {"role": "user", "content": f"[IMAGE SOURCE: {src}] {question}", "images": [part]})
        if vision_model:
            try:
                desc = llm.complete([f"[IMAGE SOURCE: {src}] {question}\nDescribe precisely what is "
                                     "relevant, including any readable text.", part],
                                    role="vision", max_tokens=600, timeout=120)
                if desc:
                    return f"[What the {angle} shows, described by the vision model]\n{desc}", None
            except Exception as e:
                self.ui.write_log(f"ERR: Vision model — {str(e)[:160]}")
        if angle != "camera":
            try:
                from core import screen_reader
                text = screen_reader.ocr_image_bytes(img_b)
                if text:
                    return ("No vision model is set, so here is the text read from the screen "
                            f"(OCR):\n{text}"), None
            except Exception:
                pass
        return ("I captured the image but no model that can see is configured. Tell the user to "
                "pick a vision model (for example qwen2.5vl:3b or gemma3:4b) in ⚙ → AI BRAIN."), None

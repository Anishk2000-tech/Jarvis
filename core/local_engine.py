"""
The local voice engine: microphone → speech recognition → any LLM with tools →
speech → speakers. Used for every brain except Gemini Live.

HOW IT FITS INTO THE EXISTING APP
    main.py's JarvisLive is built around one object, `self.session`, the Gemini
    Live connection. Everything else — the tool dispatcher, memory, undo,
    vision capture, the wake word, push-to-talk, the phone dashboard, the
    morning briefing, proactive check-ins, hardware alerts, the avatar's
    lip-sync and the echo guard — talks to that object or to two queues.

    So this engine does not rebuild any of that. It is a mixin that replaces
    exactly the parts that belonged to Gemini:

      * `self.session` becomes LocalSession, which accepts the same calls
        (send_client_content, send_realtime_input) and turns them into requests
        for the local brain;
      * the microphone feeds a voice-activity detector and speech recognition
        instead of a websocket;
      * the reply is generated by core.llm with the SAME tool declarations and
        run through the SAME `_execute_tool`, and spoken by core.tts_engine into
        the SAME `audio_in_queue` that `_play_audio` already drains — so the
        avatar's mouth, the waveform and the echo guard work unchanged.

HUMAN-LIKE CONVERSATION
    * Barge-in: speak while it is talking and it stops and listens. What the
      microphone hears during a reply is transcribed and compared with what the
      assistant just said; its own echo is ignored, a new voice interrupts.
    * Ambient mode: it listens to the whole room, keeps a local transcript, and
      answers only when called by name — or for a while after it last spoke, the
      way a person stays in a conversation they have joined.
    * It speaks the first sentence while the rest is still being written.
    * Voice confirmation: "confirm" / "cancel" answer the on-screen gate for
      shutdown, restart and dangerous commands, decided by the words heard, not
      by the model.
"""
